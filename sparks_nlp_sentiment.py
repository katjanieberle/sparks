"""#### 2.2 TF-IDF (Term Frequency-Inverse Document Frequency)

**TF-IDF** is another very popular technique for text representation that addresses one of the major drawbacks of plain Bag-of-Words: it assigns weights to words based on their importance to a document in a collection or corpus.

TF-IDF is composed of two terms:

1.  **Term Frequency (TF):** This measures how frequently a term appears in a document. Since longer documents may have a term appear more often than shorter ones, TF is often normalized by dividing the raw count by the total number of words in the document:
    
    $$ \text{TF}(t,d) = \frac{\text{Number of times term } t \text{ appears in document } d}{\text{Total number of terms in document } d} $$

2.  **Inverse Document Frequency (IDF):** This measures how important a term is across the whole corpus. Rare terms across the corpus have a high IDF score, while common terms (like stop words) have a low IDF score. It helps to penalize words that appear too frequently across many documents.
    
    $$ \text{IDF}(t,D) = \log\left(\frac{\text{Total number of documents in corpus } D}{\text{Number of documents with term } t \text{ in them}} \right) $$

    (A small smoothing factor, typically 1, is often added to the denominator to avoid division by zero for terms not in the corpus, and log is used to dampen the effect of IDF.)

Finally, the TF-IDF score is calculated by multiplying TF and IDF:

$$ \text{TF-IDF}(t,d,D) = \text{TF}(t,d) \times \text{IDF}(t,D) $$

This means a high TF-IDF score is given to words that appear frequently in a *specific* document but rarely across the *entire corpus*, making them good indicators of the document's content.

We will use `Scikit-learn`'s `TfidfVectorizer` to implement TF-IDF.
"""

